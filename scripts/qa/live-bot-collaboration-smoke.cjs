#!/usr/bin/env node

/* eslint-disable no-console */

const crypto = require("node:crypto");
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const WebSocket = require("ws");

const DEFAULT_CONTROL_PLANE_URL = "ws://127.0.0.1:18789";
const DEFAULT_TIMEOUT_MS = 120000;
const DEFAULT_POLL_MS = 1500;

function usage() {
  console.error(
    [
      "Usage:",
      "  npm run qa:bots:live -- --sender-task <id> --recipient-task <id>",
      "",
      "Required:",
      "  --sender-task <id>       Existing bot conversation that will call send_agent_message",
      "  --recipient-task <id>    Existing bot conversation that must receive and acknowledge it",
      "",
      "Options:",
      "  --marker <text>          Stable marker to send (a unique marker is generated by default)",
      "  --timeout-ms <n>         End-to-end wait budget (default: 120000)",
      "  --poll-ms <n>            Event polling interval (default: 1500)",
      "  --url <ws-url>           Control-plane WebSocket URL",
      "  --token <token>          Control-plane token",
      "  --device-name <name>     Control-plane device name",
      "  --allow-non-bot          Allow pre-existing tasks without bot metadata (diagnostic only)",
      "  --dry-run                Print the exact prompt/marker without contacting the app",
      "  --help                   Show this help",
      "",
      "Environment:",
      "  COWORK_CONTROL_PLANE_URL, COWORK_CONTROL_PLANE_TOKEN, COWORK_USER_DATA_DIR",
    ].join("\n"),
  );
}

function parseArgs(argv) {
  const args = {
    url: process.env.COWORK_CONTROL_PLANE_URL || "",
    token: process.env.COWORK_CONTROL_PLANE_TOKEN || "",
    deviceName: "cowork-bot-live-smoke",
    allowNonBot: false,
    dryRun: false,
  };

  for (let index = 0; index < argv.length; index += 1) {
    const value = argv[index];
    if (value === "--help" || value === "-h") {
      args.help = true;
      continue;
    }
    if (value === "--allow-non-bot") {
      args.allowNonBot = true;
      continue;
    }
    if (value === "--dry-run") {
      args.dryRun = true;
      continue;
    }
    if (
      value === "--sender-task" ||
      value === "--recipient-task" ||
      value === "--marker" ||
      value === "--timeout-ms" ||
      value === "--poll-ms" ||
      value === "--url" ||
      value === "--token" ||
      value === "--device-name"
    ) {
      const next = argv[index + 1];
      if (!next || next.startsWith("--")) {
        throw new Error(`${value} requires a value`);
      }
      const key = {
        "--sender-task": "senderTaskId",
        "--recipient-task": "recipientTaskId",
        "--marker": "marker",
        "--timeout-ms": "timeoutMs",
        "--poll-ms": "pollMs",
        "--url": "url",
        "--token": "token",
        "--device-name": "deviceName",
      }[value];
      args[key] = next;
      index += 1;
      continue;
    }
    throw new Error(`Unknown option: ${value}`);
  }

  return args;
}

function required(value, name) {
  const normalized = typeof value === "string" ? value.trim() : "";
  if (!normalized) throw new Error(`${name} is required`);
  return normalized;
}

function positiveInteger(value, fallback, name) {
  if (value === undefined || value === null || value === "") return fallback;
  const parsed = Number.parseInt(String(value), 10);
  if (!Number.isFinite(parsed) || parsed <= 0) throw new Error(`${name} must be a positive integer`);
  return parsed;
}

function randomSuffix() {
  return crypto.randomBytes(5).toString("hex").toUpperCase();
}

function candidateUserDataDirs() {
  const explicit = process.env.COWORK_USER_DATA_DIR;
  const profile = (process.env.COWORK_PROFILE || process.env.COWORK_PROFILE_ID || "").trim();
  const root = explicit
    ? path.resolve(explicit)
    : process.platform === "darwin"
      ? path.join(os.homedir(), "Library", "Application Support", "cowork-os")
      : process.platform === "win32"
        ? path.join(process.env.APPDATA || path.join(os.homedir(), "AppData", "Roaming"), "cowork-os")
        : path.join(os.homedir(), ".cowork");
  const dirs = [root];
  if (profile && profile !== "default") dirs.push(path.join(root, "profiles", profile));
  return Array.from(new Set(dirs));
}

function discoverConnection(args) {
  if (args.token) {
    return { url: args.url || DEFAULT_CONTROL_PLANE_URL, token: args.token, source: "environment/flags" };
  }

  for (const directory of candidateUserDataDirs()) {
    const descriptorPath = path.join(directory, "control-plane-local.json");
    try {
      const descriptor = JSON.parse(fs.readFileSync(descriptorPath, "utf8"));
      const token = typeof descriptor.token === "string" ? descriptor.token.trim() : "";
      const url = typeof descriptor.url === "string" ? descriptor.url.trim() : "";
      const pid = typeof descriptor.pid === "number" ? descriptor.pid : 0;
      if (!token || !url) continue;
      if (pid > 0) {
        try {
          process.kill(pid, 0);
        } catch {
          continue;
        }
      }
      return { url: args.url || url, token, source: descriptorPath };
    } catch {
      // Try the next profile/user-data directory.
    }
  }

  throw new Error(
    "No control-plane token found. Start CoWork OS or provide --token/COWORK_CONTROL_PLANE_TOKEN.",
  );
}

class ControlPlaneClient {
  constructor({ url, token, deviceName, timeoutMs }) {
    this.url = url;
    this.token = token;
    this.deviceName = deviceName;
    this.timeoutMs = timeoutMs;
    this.socket = null;
    this.nextId = 1;
  }

  async connect() {
    this.socket = new WebSocket(this.url);
    await new Promise((resolve, reject) => {
      const timer = setTimeout(() => reject(new Error(`Timed out connecting to ${this.url}`)), this.timeoutMs);
      const onOpen = () => {
        clearTimeout(timer);
        this.socket.off("error", onError);
        resolve();
      };
      const onError = (error) => {
        clearTimeout(timer);
        this.socket.off("open", onOpen);
        reject(error);
      };
      this.socket.once("open", onOpen);
      this.socket.once("error", onError);
    });
    await this.request("connect", { token: this.token, deviceName: this.deviceName });
  }

  request(method, params) {
    if (!this.socket || this.socket.readyState !== WebSocket.OPEN) {
      return Promise.reject(new Error("Control plane is not connected"));
    }
    const id = String(this.nextId++);
    return new Promise((resolve, reject) => {
      const timer = setTimeout(() => {
        this.socket.off("message", onMessage);
        reject(new Error(`Timed out waiting for ${method}`));
      }, this.timeoutMs);
      const onMessage = (data) => {
        let frame;
        try {
          frame = JSON.parse(String(data));
        } catch {
          return;
        }
        if (!frame || frame.type !== "res" || frame.id !== id) return;
        clearTimeout(timer);
        this.socket.off("message", onMessage);
        if (frame.ok) {
          resolve(frame.payload);
        } else {
          const error = new Error(frame.error?.message || `${method} failed`);
          error.code = frame.error?.code;
          error.details = frame.error?.details;
          reject(error);
        }
      };
      this.socket.on("message", onMessage);
      this.socket.send(
        JSON.stringify({ type: "req", id, method, ...(params === undefined ? {} : { params }) }),
      );
    });
  }

  close() {
    if (this.socket) this.socket.close();
    this.socket = null;
  }
}

function getTask(payload) {
  return payload && payload.task ? payload.task : null;
}

function getEvents(payload) {
  return payload && Array.isArray(payload.events) ? payload.events : [];
}

function eventType(event) {
  const legacyType = typeof event?.legacyType === "string" ? event.legacyType.trim() : "";
  return legacyType || String(event?.type || "");
}

function eventPayload(event) {
  return event && event.payload && typeof event.payload === "object" ? event.payload : {};
}

function deliveryStatus(payload) {
  return String(payload.deliveryStatus || payload.delivery_status || payload.status || "")
    .trim()
    .toLowerCase();
}

function eventText(event) {
  const payload = eventPayload(event);
  return [
    payload.message,
    payload.text,
    payload.content,
    payload.resultSummary,
    payload.summary,
    event?.message,
  ]
    .filter((value) => typeof value === "string")
    .join("\n");
}

function matchingSenderDelivery(events, messageId, recipientTaskId) {
  return events
    .filter((event) => {
      const payload = eventPayload(event);
      return (
        eventType(event) === "agent_message" &&
        payload.messageId === messageId &&
        payload.targetTaskId === recipientTaskId
      );
    })
    .sort((left, right) => Number(left.timestamp || 0) - Number(right.timestamp || 0))
    .at(-1);
}

function matchingReceiverReceipt(events, messageId, senderTaskId, message) {
  return events
    .filter((event) => {
      const payload = eventPayload(event);
      return (
        eventType(event) === "user_message" &&
        payload.messageId === messageId &&
        payload.senderTaskId === senderTaskId &&
        payload.message === message
      );
    })
    .sort((left, right) => Number(left.timestamp || 0) - Number(right.timestamp || 0))
    .at(-1);
}

function matchingAck(events, ackToken, afterTimestamp) {
  return events
    .filter((event) => {
      const type = eventType(event);
      return (
        Number(event.timestamp || 0) >= afterTimestamp &&
        type === "assistant_message" &&
        eventText(event).includes(ackToken)
      );
    })
    .sort((left, right) => Number(left.timestamp || 0) - Number(right.timestamp || 0))
    .at(-1);
}

function summarizeEvent(event) {
  if (!event) return null;
  const payload = eventPayload(event);
  return {
    id: event.id,
    type: eventType(event),
    timestamp: event.timestamp,
    status: deliveryStatus(payload) || undefined,
    messageId: payload.messageId,
    targetTaskId: payload.targetTaskId,
    excerpt: eventText(event).replace(/\s+/g, " ").trim().slice(0, 240) || undefined,
  };
}

function isBotConversation(task) {
  const config = task?.agentConfig || {};
  return config.botConversation === true || Boolean(config.botTeamId) || Boolean(task?.assignedAgentRoleId);
}

function taskSummary(task) {
  return {
    id: task?.id,
    title: task?.title,
    status: task?.status,
    workspaceId: task?.workspaceId,
    assignedAgentRoleId: task?.assignedAgentRoleId,
    botConversation: task?.agentConfig?.botConversation === true,
    botTeamId: task?.agentConfig?.botTeamId,
  };
}

function sleep(milliseconds) {
  return new Promise((resolve) => setTimeout(resolve, milliseconds));
}

function output(value) {
  process.stdout.write(`${JSON.stringify(value, null, 2)}\n`);
}

async function run(args) {
  if (args.help) {
    usage();
    return 0;
  }

  args.senderTaskId = required(args.senderTaskId, "--sender-task");
  args.recipientTaskId = required(args.recipientTaskId, "--recipient-task");
  if (args.senderTaskId === args.recipientTaskId) {
    throw new Error("--sender-task and --recipient-task must be different tasks");
  }
  args.timeoutMs = positiveInteger(args.timeoutMs, DEFAULT_TIMEOUT_MS, "--timeout-ms");
  args.pollMs = positiveInteger(args.pollMs, DEFAULT_POLL_MS, "--poll-ms");

  const suffix = randomSuffix();
  const marker = args.marker || `COWORK_BOT_SMOKE_${Date.now()}_${suffix}`;
  const ackToken = `COWORK_BOT_ACK_${suffix}`;
  const messageId = `cowork-live-smoke-${Date.now()}-${suffix.toLowerCase()}`;
  const message = `LIVE_COWORK_BOT_SMOKE marker=${marker}. When you receive this message, reply with the exact token ${ackToken}. Do not take any other action.`;
  const senderPrompt = [
    "Run the live CoWork Bots delivery smoke test now.",
    `Call send_agent_message exactly once with task_id "${args.recipientTaskId}".`,
    `Use message_id "${messageId}" and send this exact message: ${message}`,
    "After the tool returns, report its actual result in plain language. Do not simulate the recipient response.",
  ].join("\n");

  if (args.dryRun) {
    output({
      ok: true,
      dryRun: true,
      senderTaskId: args.senderTaskId,
      recipientTaskId: args.recipientTaskId,
      marker,
      ackToken,
      messageId,
      recipientMessage: message,
      senderPrompt,
      note: "No control-plane connection or task mutation was performed.",
    });
    return 0;
  }

  const connection = discoverConnection(args);
  const client = new ControlPlaneClient({
    url: connection.url,
    token: connection.token,
    deviceName: args.deviceName,
    timeoutMs: Math.min(args.timeoutMs, 15000),
  });
  try {
    await client.connect();
    const [senderPayload, recipientPayload] = await Promise.all([
      client.request("task.get", { taskId: args.senderTaskId }),
      client.request("task.get", { taskId: args.recipientTaskId }),
    ]);
    const senderTask = getTask(senderPayload);
    const recipientTask = getTask(recipientPayload);
    if (!senderTask || !recipientTask) throw new Error("The sender or recipient task was not found");
    if (senderTask.workspaceId !== recipientTask.workspaceId) {
      throw new Error(
        `Bot smoke requires one workspace; sender=${senderTask.workspaceId} recipient=${recipientTask.workspaceId}`,
      );
    }
    if ((!isBotConversation(senderTask) || !isBotConversation(recipientTask)) && !args.allowNonBot) {
      const error = new Error(
        "Both tasks must be persistent bot conversations. Use --allow-non-bot only for a diagnostic run.",
      );
      error.details = { sender: taskSummary(senderTask), recipient: taskSummary(recipientTask) };
      throw error;
    }

    const [senderBefore, recipientBefore] = await Promise.all([
      client.request("task.events", { taskId: args.senderTaskId, limit: 400 }),
      client.request("task.events", { taskId: args.recipientTaskId, limit: 400 }),
    ]);

    const promptResponse = await client.request("task.sendMessage", {
      taskId: args.senderTaskId,
      message: senderPrompt,
      messageId: `cowork-live-prompt-${Date.now()}-${suffix.toLowerCase()}`,
      returnOnAccepted: true,
    });

    const startedAt = Date.now();
    let lastSnapshot = {
      senderTask: taskSummary(senderTask),
      recipientTask: taskSummary(recipientTask),
      senderDelivery: null,
      receiverReceipt: null,
      receiverAck: null,
    };

    while (Date.now() - startedAt < args.timeoutMs) {
      const [senderState, recipientState, senderEventsPayload, recipientEventsPayload] = await Promise.all([
        client.request("task.get", { taskId: args.senderTaskId }),
        client.request("task.get", { taskId: args.recipientTaskId }),
        client.request("task.events", { taskId: args.senderTaskId, limit: 400 }),
        client.request("task.events", { taskId: args.recipientTaskId, limit: 400 }),
      ]);
      const senderEvents = getEvents(senderEventsPayload);
      const recipientEvents = getEvents(recipientEventsPayload);
      const senderDelivery = matchingSenderDelivery(senderEvents, messageId, args.recipientTaskId);
      const receiverReceipt = matchingReceiverReceipt(
        recipientEvents,
        messageId,
        args.senderTaskId,
        message,
      );
      const receiverAck = matchingAck(recipientEvents, ackToken, startedAt);
      lastSnapshot = {
        senderTask: taskSummary(getTask(senderState)),
        recipientTask: taskSummary(getTask(recipientState)),
        senderDelivery: summarizeEvent(senderDelivery),
        receiverReceipt: summarizeEvent(receiverReceipt),
        receiverAck: summarizeEvent(receiverAck),
      };

      const deliveryStatus = deliveryStatus(eventPayload(senderDelivery));
      const receiptStatus = deliveryStatus(eventPayload(receiverReceipt));
      if (deliveryStatus === "failed" || deliveryStatus === "quarantined") {
        output({
          ok: false,
          stage: "delivery",
          connectionSource: connection.source,
          marker,
          ackToken,
          messageId,
          promptResponse,
          ...lastSnapshot,
          senderEvents: senderEvents.slice(-8).map(summarizeEvent),
          recipientEvents: recipientEvents.slice(-8).map(summarizeEvent),
        });
        return 2;
      }
      if (deliveryStatus === "delivered" && receiptStatus === "delivered" && receiverAck) {
        output({
          ok: true,
          stage: "complete",
          connectionSource: connection.source,
          marker,
          ackToken,
          messageId,
          workspaceId: senderTask.workspaceId,
          promptResponse,
          ...lastSnapshot,
          proof: {
            senderReceipt: "agent_message deliveryStatus=delivered",
            receiverTranscript: "user_message deliveryStatus=delivered",
            receiverCompletion: `assistant event contained ${ackToken}`,
          },
        });
        return 0;
      }
      await sleep(args.pollMs);
    }

    const [senderAfter, recipientAfter] = await Promise.all([
      client.request("task.events", { taskId: args.senderTaskId, limit: 400 }),
      client.request("task.events", { taskId: args.recipientTaskId, limit: 400 }),
    ]);
    output({
      ok: false,
      stage: "timeout",
      connectionSource: connection.source,
      timeoutMs: args.timeoutMs,
      marker,
      ackToken,
      messageId,
      promptResponse,
      ...lastSnapshot,
      senderEvents: getEvents(senderAfter).slice(-12).map(summarizeEvent),
      recipientEvents: getEvents(recipientAfter).slice(-12).map(summarizeEvent),
      baselineCounts: {
        sender: getEvents(senderBefore).length,
        recipient: getEvents(recipientBefore).length,
      },
      hint: "A timeout is a live failure, not a pass. Inspect the sender receipt, receiver receipt, and receiver acknowledgement separately.",
    });
    return 2;
  } finally {
    client.close();
  }
}

if (require.main === module) {
  run(parseArgs(process.argv.slice(2)))
    .then((exitCode) => {
      process.exitCode = exitCode;
    })
    .catch((error) => {
      output({
        ok: false,
        stage: "preflight",
        error: error?.message || String(error),
        ...(error?.code ? { code: error.code } : {}),
        ...(error?.details ? { details: error.details } : {}),
      });
      process.exitCode = 2;
    });
}

module.exports = {
  eventType,
  matchingAck,
  matchingReceiverReceipt,
  matchingSenderDelivery,
};
