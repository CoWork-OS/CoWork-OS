#!/usr/bin/env node
/**
 * Regenerates src/shared/model-metadata.json from the models.dev catalogue.
 *
 * The snapshot is the source of truth for per-token prices and context limits
 * used by src/electron/agent/llm/pricing.ts and context-manager.ts, so model
 * prices no longer have to be maintained by hand.
 *
 * Usage:
 *   node scripts/sync-model-metadata.mjs                 # fetch https://models.dev/api.json
 *   node scripts/sync-model-metadata.mjs --input api.json  # use a downloaded copy
 *   node scripts/sync-model-metadata.mjs --check           # exit 1 if the snapshot is stale
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
// Node 24 strips TypeScript types natively; the transform is shared with the app.
import { MODELS_DEV_URL, buildModelMetadata } from "../src/shared/model-metadata-build.ts";

const here = path.dirname(fileURLToPath(import.meta.url));
const OUTPUT_PATH = path.resolve(here, "../src/shared/model-metadata.json");

export function buildSnapshot(catalogue, generatedAt) {
  return {
    source: MODELS_DEV_URL,
    generatedAt,
    note: "Generated by scripts/sync-model-metadata.mjs. Do not edit by hand; add exceptions to src/electron/agent/llm/pricing-overrides.ts.",
    models: buildModelMetadata(catalogue),
  };
}

async function loadCatalogue(inputPath) {
  if (inputPath) return JSON.parse(fs.readFileSync(inputPath, "utf8"));
  const response = await fetch(MODELS_DEV_URL, { headers: { accept: "application/json" } });
  if (!response.ok) throw new Error(`models.dev returned HTTP ${response.status}`);
  return response.json();
}

async function main() {
  const args = process.argv.slice(2);
  const inputIndex = args.indexOf("--input");
  const inputPath = inputIndex >= 0 ? args[inputIndex + 1] : undefined;
  const check = args.includes("--check");

  const catalogue = await loadCatalogue(inputPath);
  const today = new Date().toISOString().slice(0, 10);
  const next = buildSnapshot(catalogue, today);

  const current = fs.existsSync(OUTPUT_PATH) ? JSON.parse(fs.readFileSync(OUTPUT_PATH, "utf8")) : null;
  const unchanged = current && JSON.stringify(current.models) === JSON.stringify(next.models);

  if (check) {
    if (!unchanged) {
      process.stderr.write("model-metadata.json is out of date; run npm run models:sync\n");
      process.exit(1);
    }
    process.stdout.write("model-metadata.json is up to date\n");
    return;
  }
  if (unchanged) {
    process.stdout.write(`No model changes (${Object.keys(next.models).length} models)\n`);
    return;
  }
  fs.writeFileSync(OUTPUT_PATH, `${JSON.stringify(next, null, 2)}\n`);
  process.stdout.write(`Wrote ${Object.keys(next.models).length} models to ${path.relative(process.cwd(), OUTPUT_PATH)}\n`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((error) => {
    process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`);
    process.exit(1);
  });
}
